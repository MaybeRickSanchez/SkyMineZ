    {
    }

    /**
     * Reads `messages.<key>` from config.yml with a built-in fallback, then
     * substitutes {placeholders}.
     *
     * @param array<string, string|int|float|bool> $placeholders
     */
    public static function get(
        Main $main,
        string $key,
        array $placeholders = []
    ): string {
        $template = $main->getConfigManager()->getString(
            'messages.' . $key,
            self::DEFAULTS[$key] ?? ''
        );

        if ($template === '' && isset(self::DEFAULTS[$key])) {
            $template = self::DEFAULTS[$key];
        }

        foreach ($placeholders as $name => $value) {
            $template = str_replace(
                '{' . $name . '}',
                is_bool($value) ? ($value ? 'true' : 'false') : (string) $value,
                $template
            );
        }

        return $template;
    }

    /**
     * Sends the prefixed message for $key.
     *
     * @param array<string, string|int|float|bool> $placeholders
     */
    public static function send(
        CommandSender $sender,
        Main $main,
        string $key,
        array $placeholders = []
    ): void {
        $sender->sendMessage(
            $main->getConfigManager()->getPrefix()
            . self::get($main, $key, $placeholders)
        );
    }
}
