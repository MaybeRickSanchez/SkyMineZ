 *    BaseCommand::error()/success()/info() carry NO leading color code; the
 *    helper adds §c / §a / §7 itself.
 *  - defaults sent via sendMessage()/broadcastMessage() with the prefix
 *    prepended carry their FULL colors, exactly as they should appear.
